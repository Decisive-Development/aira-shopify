#!/usr/bin/env node
/*
  Writes snippets/critical-css.liquid from assets/critical.css.

  The compiled Tailwind stylesheet is inlined into <head> so first paint does
  not wait on a stylesheet request. Shopify's inline_asset_content filter
  refuses assets over 15 KB, so the CSS goes through a generated snippet that
  the layouts render inside <style>. assets/critical.css stays as the build
  intermediate and is listed in .shopifyignore.

  Run by `npm run build:css`. With --watch it regenerates whenever the
  Tailwind watcher rewrites assets/critical.css.
*/
const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..');
const input = path.join(root, 'assets', 'critical.css');
const output = path.join(root, 'snippets', 'critical-css.liquid');
const header = '{% comment %}Generated by scripts/build-critical-snippet.js from assets/critical.source.css via npm run build:css. Do not edit.{% endcomment %}';

function build() {
  const css = fs.readFileSync(input, 'utf8').trim();
  if (css.includes('{% endraw %}')) {
    throw new Error('assets/critical.css contains "{% endraw %}", which would close the raw block early.');
  }
  fs.writeFileSync(output, header + '\n{% raw %}' + css + '{% endraw %}\n');
  console.log('snippets/critical-css.liquid: ' + (fs.statSync(output).size / 1024).toFixed(1) + ' KB');
}

build();

if (process.argv.includes('--watch')) {
  fs.watchFile(input, { interval: 500 }, function () {
    try { build(); } catch (e) { console.error(e.message); }
  });
}
